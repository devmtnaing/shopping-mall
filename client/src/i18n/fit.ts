const TABLES: Record<string, Partial<Record<FitKey, string>> | undefined> = { en: fitEn, my: fitMy };

/** A fit string in the visitor's language, with {placeholders} filled. */
export function tf(key: FitKey, vars?: Record<string, string>): string {
  let s = TABLES[locale.value]?.[key] ?? fitEn[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}
export const measureName = (m: Measure) => tf(`fit.measure.${m}`);
export const statusName = (s: Status) => tf(`fit.status.${s}`);
